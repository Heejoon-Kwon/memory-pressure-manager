const assert = require('node:assert/strict');
global.chrome = {runtime:{onInstalled:{addListener(){}},onStartup:{addListener(){}},onMessage:{addListener(){}}},alarms:{onAlarm:{addListener(){}}},tabs:{onRemoved:{addListener(){}}}};
const {eligible, cycle, applyCommands} = require('../chrome-extension/background.js');
const tab = {id:1,url:'https://example.com/',active:false,pinned:false,audible:false,discarded:false,incognito:false};
const setting = {url:tab.url,priority:999};
assert.equal(eligible({tab,setting}),true);
for (const flag of ['active','pinned','audible','discarded','incognito']) assert.equal(eligible({tab:{...tab,[flag]:true},setting}),false,flag);
assert.equal(eligible({tab,setting:undefined}),true);
assert.equal(eligible({tab,setting:{...setting,url:'https://other.example/'}}),true);
assert.equal(eligible({tab,setting:{...setting,priority:0}}),false);
assert.equal(eligible({tab,setting:{...setting,priority:1000}}),true);
assert.equal(eligible({tab:{...tab,url:'chrome://settings/'},setting:{url:'chrome://settings/',priority:1}}),false);

(async () => {
  let discarded = [];
  let state = {tabIdentities: {1: {url: tab.url, token: 'session-a'}}, tabPriorities: {}};
  chrome.tabs.get = async () => tab;
  chrome.tabs.discard = async id => discarded.push(id);
  chrome.storage = {session: {get: async () => state, set: async obj => {state = {...state, ...obj};}}};
  chrome.runtime.sendNativeMessage = async () => ({critical: true, discard_allowed:true});
  await applyCommands([{id: 1, token: 'session-a', action: 'discard', expires: Date.now()/1000+10}]);
  assert.deepEqual(discarded, [1]);
  await applyCommands([{id: 1, token: 'session-a', priority: 0}]);
  assert.equal(state.tabPriorities[1].priority, 0);
  await applyCommands([{id: 1, token: 'session-a', action: 'discard', expires: Date.now()/1000+10}]);
  assert.deepEqual(discarded, [1]);
  await applyCommands([{id: 1, token: 'stale-session', priority: 900}]);
  assert.equal(state.tabPriorities[1].priority, 0);
  await applyCommands([{id: 1, token: 'session-a', priority: 500}]);
  await applyCommands([{id: 1, token: 'session-a', action: 'discard', expires: 0}]);
  assert.deepEqual(discarded, [1]);
  chrome.storage.local = {get: async () => ({probeProfileId:'11111111-1111-4111-8111-111111111111'})};
  chrome.scripting = {executeScript: async () => [{result:true}]};
  let focused = false;
  chrome.windows = {get: async () => ({focused})};
  let closed = [];
  chrome.tabs.remove = async id => closed.push(id);
  tab.active = true;
  await applyCommands([{id:1,token:'session-a',action:'close_web_app',expires:Date.now()/1000+10}]);
  assert.deepEqual(closed,[1]);
  focused = true;
  await applyCommands([{id:1,token:'session-a',action:'close_web_app',expires:Date.now()/1000+10}]);
  assert.deepEqual(closed,[1]);
})().catch(error => {console.error(error); process.exitCode = 1;});
